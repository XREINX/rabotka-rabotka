package ru.mirea.part2; // объявление пакета для практической части 2

public class TestBall { // тестирующий класс для проверки класса Ball
    public static void main(String[] args) { // главный метод программы
        Ball ball = new Ball(50.0, 75.0); // создаем мяч с координатами (50.0, 75.0)
        System.out.println("Исходное состояние: " + ball); // выводим начальные координаты мяча

        ball.move(15.5, -10.5); // смещаем мяч: +15.5 по оси X и -10.5 по оси Y
        System.out.println("После вызова move(15.5, -10.5): " + ball); // печатаем новые координаты мяча

        ball.setXY(0.0, 0.0); // сбрасываем координаты мяча в начало координат (0, 0)
        System.out.println("После сброса setXY(0.0, 0.0): " + ball); // проверяем сброс координат
    } // конец метода main
} // конец класса TestBall
